// Writes supabase/setup-all.sql: every migration in order, then the demo seed.
// Paste the result into Supabase → SQL editor once, on an EMPTY project (or one that only has `waitlist`).
//   node scripts/supabase/bundle.mjs            (with seed)
//   node scripts/supabase/bundle.mjs --no-seed
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const root = new URL("../../supabase/", import.meta.url).pathname;
const migrations = readdirSync(join(root, "migrations")).filter((f) => /^\d{4}_.*\.sql$/.test(f)).sort();
const parts = [
  "-- Nonnina: full database setup (generated by scripts/supabase/bundle.mjs, do not edit by hand).",
  `-- Migrations: ${migrations.join(", ")}`,
  "begin;",
];
for (const f of migrations) parts.push(`\n-- ======== ${f} ========\n`, readFileSync(join(root, "migrations", f), "utf8"));
if (!process.argv.includes("--no-seed")) parts.push("\n-- ======== seed.sql (demo data, profiles labelled as demo) ========\n", readFileSync(join(root, "seed.sql"), "utf8"));
parts.push("\ncommit;\n");
writeFileSync(join(root, "setup-all.sql"), parts.join("\n"));
console.log(`supabase/setup-all.sql: ${migrations.length} migrations${process.argv.includes("--no-seed") ? "" : " + seed"}`);
